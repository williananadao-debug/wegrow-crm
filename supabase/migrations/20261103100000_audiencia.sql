-- Módulo de Audiência (03/11/2026): pesquisas de audiência por emissora, usadas na proposta
-- (impactos, GRP, custo por mil) e nos horários sugeridos.
--
-- audiencia_pesquisas → uma pesquisa (fonte, praça, período, público) de UMA emissora (unidade)
-- audiencia_faixas    → os números por dia da semana e faixa horária dessa pesquisa
--
-- Fonte: 'kantar_ibope' (planilha exportada do Easy Media pela rádio assinante), 'instituto'
-- (pesquisa regional), 'streaming' (ouvintes do player/automação) ou 'manual'.

create table if not exists public.audiencia_pesquisas (
  id              bigint generated by default as identity primary key,
  empresa_id      uuid not null references public.empresas(id) on delete cascade,
  unidade         text not null,                     -- nome da emissora (unidades.nome)
  fonte           text not null default 'manual' check (fonte in ('kantar_ibope', 'instituto', 'streaming', 'manual')),
  instituto       text,                              -- ex.: 'Kantar IBOPE Media', 'Instituto X'
  praca           text,                              -- ex.: 'Grande Florianópolis', 'Alto Vale'
  publico         text not null default 'Total',     -- ex.: 'Total 10+', 'Mulheres 25-49 AB'
  universo        integer,                           -- população do público na praça
  periodo_inicio  date,
  periodo_fim     date,
  observacao      text,
  ativa           boolean not null default true,     -- a usada na proposta é a ativa mais recente
  criado_por      uuid references auth.users(id) on delete set null,
  created_at      timestamptz not null default now()
);
create index if not exists audiencia_pesquisas_empresa_idx on public.audiencia_pesquisas (empresa_id, unidade, periodo_fim desc);

create table if not exists public.audiencia_faixas (
  id               bigint generated by default as identity primary key,
  pesquisa_id      bigint not null references public.audiencia_pesquisas(id) on delete cascade,
  empresa_id       uuid not null references public.empresas(id) on delete cascade,
  dia_tipo         text not null default 'seg_sex' check (dia_tipo in ('seg_sex', 'sab', 'dom', 'seg_dom')),
  hora_inicio      time not null,
  hora_fim         time not null,
  ouvintes_minuto  numeric,   -- OPM: ouvintes por minuto (média da faixa)
  audiencia_pct    numeric,   -- audiência % sobre o universo
  share_pct        numeric,   -- participação % entre as rádios
  alcance          numeric    -- ouvintes distintos na faixa (quando a pesquisa traz)
);
create index if not exists audiencia_faixas_pesquisa_idx on public.audiencia_faixas (pesquisa_id, dia_tipo, hora_inicio);

alter table public.audiencia_pesquisas enable row level security;
alter table public.audiencia_faixas enable row level security;

drop policy if exists audiencia_pesquisas_empresa on public.audiencia_pesquisas;
create policy audiencia_pesquisas_empresa on public.audiencia_pesquisas
  for all to authenticated
  using (empresa_id = (select public.meu_empresa_id()))
  with check (empresa_id = (select public.meu_empresa_id()));

drop policy if exists audiencia_faixas_empresa on public.audiencia_faixas;
create policy audiencia_faixas_empresa on public.audiencia_faixas
  for all to authenticated
  using (empresa_id = (select public.meu_empresa_id()))
  with check (empresa_id = (select public.meu_empresa_id()));

grant select, insert, update, delete on public.audiencia_pesquisas, public.audiencia_faixas to authenticated;
grant all on public.audiencia_pesquisas, public.audiencia_faixas to service_role;
